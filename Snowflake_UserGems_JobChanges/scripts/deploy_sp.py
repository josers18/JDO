#!/usr/bin/env python3
"""Deploy SP_GENERATE_USERGEMS_JOB_CHANGES into DATA_JEDAIS.FINS__PUBLIC.

Clone of Plan 10's `Snowflake_BoardEx_ExecIntel/scripts/deploy_sp.py`
(template v1.5 inline-source deploy), plus an L2 fixture build.

What this script does (production, the default):
  1. Read the SP body from `procedures/sp_generate_usergems_job_changes.py`.
  2. Read `seed_for` from `Snowflake_Cumulus_Common/cumulus_common/seed.py`
     (the only shared helper the SP uses; `assert_coverage` is replaced by
     the SP's own `_assert_event_contract`).
  3. Strip the module docstring and the `from __future__` / `from
     cumulus_common` lines, splice the helper in after the last top-level
     import.
  4. Write one inline-source `CREATE OR REPLACE PROCEDURE ...` file at
     `procedures/sp_create_procedure.sql`.
  5. Run `/opt/homebrew/bin/snow sql -f procedures/sp_create_procedure.sql`
     UNFLAGGED (the active default connection; pass --connection only to
     override).

L2 fixture build (`--fixture-schema DB.SCHEMA`):
  Writes `tests/integration/sp_create_fixture_procedure.sql` (gitignored)
  holding `CREATE SCHEMA IF NOT EXISTS` plus TWO procedures in the scratch
  schema, retargeted by swapping the module's `_DB` / `_SCHEMA` lines:
    - `<schema>.SP_GENERATE_USERGEMS_JOB_CHANGES`        week band --week-band (default 0,25)
    - `<schema>.SP_GENERATE_USERGEMS_JOB_CHANGES_STRICT` week band (30, 200), production
  Both read the run clock from `<schema>.L2_RUN_CLOCK` (`_RUN_TS_SQL`) and
  log under a `..._FIXTURE` TASK_NAME so the scratch TASK_EXECUTION_LOG
  can tell the two apart. No DATA_JEDAIS reference survives the build.
  Then runs it. The L2 SQL (tests/integration/test_usergems_job_changes_sp.sql)
  creates the fixtures, calls both procs and DROPs the schema at the end.

Why a scratch schema, not FINS__PUBLIC fixtures: the default role (SYSADMIN)
has CREATE PROCEDURE / CREATE TASK on DATA_JEDAIS.FINS__PUBLIC but no
CREATE TABLE, and owns DEMO_DB. The production deploy runs with
`--role ACCOUNTADMIN`, which owns the schema and every sibling object
(Plan 14 / 16 pattern). The SP is EXECUTE AS CALLER (like the BoardEx
sibling), so its rights come from whoever calls it; the TASK and every
sibling procedure, task and table are ACCOUNTADMIN-owned, so the SP and
TASK are deployed and owned as ACCOUNTADMIN too.

Signature: `(BACKFILL_WEEKS INTEGER DEFAULT 0)`. If it ever changes, add a
`DROP PROCEDURE IF EXISTS <fqn>(<old types>);` line to SQL_HEADER first
(Snowflake overloads on signature; CREATE OR REPLACE would leave the old one).

Usage:
    python3 scripts/deploy_sp.py [--role ROLE] [--connection NAME] [--no-deploy]
    python3 scripts/deploy_sp.py --fixture-schema DEMO_DB.CUMULUS_L2_USERGEMS [--week-band 0,25]
"""
from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys


REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
SP_PY = REPO_ROOT / "procedures" / "sp_generate_usergems_job_changes.py"
SP_SQL = REPO_ROOT / "procedures" / "sp_create_procedure.sql"
FIXTURE_SQL = REPO_ROOT / "tests" / "integration" / "sp_create_fixture_procedure.sql"

CUMULUS_COMMON_ROOT = REPO_ROOT.parent / "Snowflake_Cumulus_Common" / "cumulus_common"
SEED_PY = CUMULUS_COMMON_ROOT / "seed.py"

SNOW = "/opt/homebrew/bin/snow"
PROD_DB, PROD_SCHEMA = "DATA_JEDAIS", "FINS__PUBLIC"
PROC_NAME = "SP_GENERATE_USERGEMS_JOB_CHANGES"
PROCEDURE_FQN = f"{PROD_DB}.{PROD_SCHEMA}.{PROC_NAME}"
TABLE_FQN = f"{PROD_DB}.{PROD_SCHEMA}.USERGEMS_JOB_CHANGES"
TASK_NAME = "TASK_WEEKLY_USERGEMS_JOB_CHANGES"
PROD_BAND = (30, 200)

SQL_HEADER = f"""\
-- =============================================================================
-- {PROCEDURE_FQN}  (Snowpark Python SP)
-- =============================================================================
-- Plan:    docs/superpowers/plans/2026-11-02-cumulus-plan-15-usergems-job-changes.md
-- Task:    Plan 15 T4
-- Source:  procedures/sp_generate_usergems_job_changes.py
--          (cumulus_common.seed_for inlined, no IMPORTS / no stage).
--          Generated by scripts/deploy_sp.py; do NOT edit by hand.
--
-- Shape:    EVENT-scoped. PK (ORG_ID, EVENT_ID); MERGE keys on both.
--           PROFILE_WEEK = Monday of the DETECTED_DATE week.
-- Audience: employers = BUSINESS anchors, COALESCE(CLIENT_CATEGORY,'') <> 'Household'
--           (6,435); Wealth pool = CLIENT_CATEGORY 'Wealth Management' (3,920).
-- Cadence:  WEEKLY ({TASK_NAME}), Monday 09:00 UTC.
--           BACKFILL_WEEKS=0: last complete week + the current partial week.
--           BACKFILL_WEEKS=104: one-shot 24-month backfill.
-- Gate:     BoardEx (Plan 10) is a hard dependency. A FALSE->TRUE rise of
--           EXEC_TURNOVER_FLAG in month M emits exactly one C-suite Departed
--           in M; no C-suite Departed outside a rise month; missing M-1 row
--           = no rise.
-- Contract: (a) [30,200] rows per complete week, (b) employer audience,
--           (c) Wealth pool, (d) BoardEx gate both directions. Raises.
-- RECORD_ID: SQL form of record_id_for(ORG_ID, EVENT_ID) in the MERGE
--           source SELECT, written on INSERT + UPDATE.
-- Casts:    3 DATEs + GENERATED_AT staged as NUMBER ns (write_pandas) ->
--           TO_DATE(TO_TIMESTAMP_NTZ(x::NUMBER / 1e9)); 3 BOOLEANs ::BOOLEAN.
-- =============================================================================

CREATE OR REPLACE PROCEDURE {PROCEDURE_FQN}(
    BACKFILL_WEEKS INTEGER DEFAULT 0
)
RETURNS STRING
LANGUAGE PYTHON
RUNTIME_VERSION = '3.11'
PACKAGES = ('snowflake-snowpark-python', 'pandas')
HANDLER = 'main'
EXECUTE AS CALLER
AS
$$
"""

SQL_FOOTER = "$$;\n"


def _strip_module_docstring_and_imports(src: str) -> str:
    src = re.sub(r'^\s*"""[\s\S]*?"""\s*\n', "", src, count=1)
    src = re.sub(r"^from __future__ import .*\n", "", src, flags=re.MULTILINE)
    src = re.sub(r"^from cumulus_common(?:\.[\w]+)? import .*\n", "", src, flags=re.MULTILINE)
    return src


def _extract_helper(src: str, func_name: str) -> str:
    """Top-level `def func_name(...)` with its body (stops at the next column-0 line)."""
    out: list[str] = []
    in_func = False
    for line in src.splitlines(keepends=True):
        if not in_func:
            if line.startswith(f"def {func_name}("):
                in_func = True
                out.append(line)
            continue
        if line and line[0] not in (" ", "\t", "\n", "#"):
            break
        out.append(line)
    if not out:
        raise RuntimeError(f"could not find `def {func_name}` in source")
    while out and out[-1].strip() == "":
        out.pop()
    return "".join(out) + "\n"


def build_body() -> str:
    """Self-contained Python source of the production SP."""
    sp_clean = _strip_module_docstring_and_imports(SP_PY.read_text())
    seed_for_def = _extract_helper(SEED_PY.read_text(), "seed_for")
    inlined = (
        "import hashlib\n\n"
        "# -------------------------------------------------------------------\n"
        "# Inlined copy of cumulus_common.seed.seed_for (kept in sync via scripts/deploy_sp.py)\n"
        "# -------------------------------------------------------------------\n"
        f"{seed_for_def}\n"
    )
    lines = sp_clean.splitlines(keepends=True)
    last_import = max((i for i, l in enumerate(lines)
                       if l.startswith("import ") or l.startswith("from ")), default=-1)
    if last_import < 0:
        raise RuntimeError("no import lines found in cleaned SP body; refusing to splice")
    at = last_import + 1
    while at < len(lines) and lines[at].strip() == "":
        at += 1
    return ("from __future__ import annotations\n\n" + "".join(lines[:at]) + "\n"
            + inlined + "\n" + "".join(lines[at:]))


def build_sql() -> str:
    sql = SQL_HEADER + build_body() + SQL_FOOTER
    if "&" in sql:
        raise RuntimeError("bare '&' in generated SQL (snow sql templating trap)")
    return sql


def _sub_once(pattern: str, repl: str, src: str) -> str:
    out, n = re.subn(pattern, repl, src, count=1, flags=re.MULTILINE)
    if n != 1:
        raise RuntimeError(f"fixture build: pattern not found: {pattern}")
    return out


def _fixture_body(schema_fqn: str, band: tuple[int, int], task_suffix: str) -> str:
    db, schema = schema_fqn.split(".")
    body = build_body()
    body = _sub_once(r'^_DB = "DATA_JEDAIS"$', f'_DB = "{db}"', body)
    body = _sub_once(r'^_SCHEMA = "FINS__PUBLIC"$', f'_SCHEMA = "{schema}"', body)
    body = _sub_once(r"^_RUN_TS_SQL = None$",
                     f'_RUN_TS_SQL = "SELECT RUN_TS FROM {schema_fqn}.L2_RUN_CLOCK"', body)
    body = _sub_once(r"^_WEEK_ROWS_MIN = \d+$", f"_WEEK_ROWS_MIN = {int(band[0])}", body)
    body = _sub_once(r"^_WEEK_ROWS_MAX = \d+$", f"_WEEK_ROWS_MAX = {int(band[1])}", body)
    body = _sub_once(r'^(TASK_NAME\s*=\s*)"TASK_WEEKLY_USERGEMS_JOB_CHANGES"$',
                     rf'\1"TASK_WEEKLY_USERGEMS_JOB_CHANGES{task_suffix}"', body)
    return body.replace(f"{PROD_DB}.{PROD_SCHEMA}", schema_fqn)


def _fixture_proc(fqn: str, body: str) -> str:
    return (f"CREATE OR REPLACE PROCEDURE {fqn}(\n    BACKFILL_WEEKS INTEGER DEFAULT 0\n)\n"
            "RETURNS STRING\nLANGUAGE PYTHON\nRUNTIME_VERSION = '3.11'\n"
            "PACKAGES = ('snowflake-snowpark-python', 'pandas')\n"
            "HANDLER = 'main'\nEXECUTE AS CALLER\nAS\n$$\n" + body + SQL_FOOTER)


def build_fixture_sql(schema_fqn: str, band: tuple[int, int] = (0, 25)) -> str:
    if not re.fullmatch(r"[A-Z0-9_]+\.[A-Z0-9_]+", schema_fqn):
        raise ValueError(f"--fixture-schema must be DB.SCHEMA (upper case), got {schema_fqn!r}")
    if schema_fqn.split(".")[0] == PROD_DB:
        raise ValueError("fixture schema must not live in the production database")
    loose = _fixture_proc(f"{schema_fqn}.{PROC_NAME}", _fixture_body(schema_fqn, band, "_FIXTURE"))
    strict = _fixture_proc(f"{schema_fqn}.{PROC_NAME}_STRICT",
                           _fixture_body(schema_fqn, PROD_BAND, "_STRICT_FIXTURE"))
    sql = (
        "-- L2 fixture procedures for SP_GENERATE_USERGEMS_JOB_CHANGES.\n"
        "-- Generated by scripts/deploy_sp.py --fixture-schema; gitignored; do NOT edit.\n"
        f"CREATE SCHEMA IF NOT EXISTS {schema_fqn};\n\n" + loose + "\n" + strict
    )
    if PROD_DB in sql:
        raise RuntimeError("fixture build leaked a production reference")
    if "&" in sql:
        raise RuntimeError("bare '&' in generated fixture SQL")
    return sql


def build_snow_cmd(path, connection: str | None = None, role: str | None = None) -> list[str]:
    """`snow sql -f <path>` on the active default connection. `-c` only on an
    explicit override (an OAuth connection opens a browser popup); `--role`
    forwarded when given (sibling objects are owned by ACCOUNTADMIN)."""
    cmd = [SNOW, "sql", "-f", str(path)]
    if connection:
        cmd[2:2] = ["-c", connection]
    if role:
        cmd += ["--role", role]
    return cmd


def _run(path: pathlib.Path, connection: str | None, role: str | None = None) -> int:
    cmd = build_snow_cmd(path, connection, role)
    print(f"Running: {' '.join(cmd)}")
    return subprocess.call(cmd)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--connection", "-c", default=None,
                        help="snow connection override (default: unflagged active connection)")
    parser.add_argument("--role", default=None,
                        help="role passed to snow sql (default: ACCOUNTADMIN, which owns the siblings; "
                             "with --fixture-schema, the connection's default role, as the L2 runs as SYSADMIN)")
    parser.add_argument("--no-deploy", action="store_true",
                        help="write the SQL file but skip snow sql -f")
    parser.add_argument("--fixture-schema", default=None,
                        help="build the L2 fixture procs into DB.SCHEMA instead of production")
    parser.add_argument("--week-band", default="0,25",
                        help="contract (a) band for the loose fixture proc (default 0,25)")
    args = parser.parse_args()

    for path in (SP_PY, SEED_PY):
        if not path.exists():
            print(f"ERROR: {path} does not exist", file=sys.stderr)
            return 1

    if args.fixture_schema:
        lo, hi = (int(x) for x in args.week_band.split(","))
        sql, out = build_fixture_sql(args.fixture_schema, (lo, hi)), FIXTURE_SQL
    else:
        sql, out = build_sql(), SP_SQL
    out.write_text(sql)
    print(f"wrote {out} ({len(sql)} bytes)")
    if args.no_deploy:
        return 0
    role = args.role or (None if args.fixture_schema else "ACCOUNTADMIN")
    rc = _run(out, args.connection, role)
    if rc != 0:
        print(f"ERROR: snow sql exited with code {rc}", file=sys.stderr)
    return rc


if __name__ == "__main__":
    sys.exit(main())
