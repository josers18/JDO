#!/usr/bin/env python3
"""Deploy SP_GENERATE_DEMANDBASE_INTENT_SIGNALS into DATA_JEDAIS.FINS__PUBLIC.

Clone of Plan 12's `Snowflake_Gong_CallSentiment/scripts/deploy_sp.py`
(weekly cadence, two salts), with the Plan 14 deltas:

  - Signature `(BACKFILL_WEEKS INTEGER DEFAULT 0)`. 0 = current week only
    (the TASK path, no-arg form); N > 0 = weeks W-N .. W ascending, each
    rewritten wholesale (DELETE the week + INSERT, one transaction). If a
    prior deploy used a different signature, DROP that overload first
    (`--drop-old-signature` emits the DROP for the no-arg form).
  - Three inlined helpers instead of two: `seed_for`, `assert_coverage` and
    `record_id_for` (RECORD_ID = record_id_for(ORG_ID, ACCOUNT_ID,
    PROFILE_WEEK, INTENT_TOPIC)), read from the sibling
    `Snowflake_Cumulus_Common/cumulus_common/` package (read-only here).
  - The generated SQL is rejected if it contains an ampersand (snow sql
    template-render trap) or a second `$$` (would end the dollar-quoted
    body early).

What this script does:
  1. Read the SP body from `procedures/sp_generate_demandbase_intent_signals.py`.
  2. Strip the module docstring, `from __future__` and `from cumulus_common...`
     imports; inline the three helpers after the top-level import block.
  3. Write a single inline-source `CREATE OR REPLACE PROCEDURE ...` to
     `procedures/sp_create_procedure.sql` (no IMPORTS / no stage -- the org
     has no internal stage, and inter-SP imports are unsupported).
  4. Run it with an UNFLAGGED `snow sql -f <file>` (default JWT connection;
     passing -c to an OAuth connection opens a browser popup).

Usage:
    python scripts/deploy_sp.py [--no-deploy] [--drop-old-signature] [--connection NAME]
"""
from __future__ import annotations

import argparse
import pathlib
import re
import shutil
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
SP_PY = REPO_ROOT / "procedures" / "sp_generate_demandbase_intent_signals.py"
SP_SQL = REPO_ROOT / "procedures" / "sp_create_procedure.sql"

CUMULUS_COMMON_ROOT = REPO_ROOT.parent / "Snowflake_Cumulus_Common" / "cumulus_common"
SEED_PY = CUMULUS_COMMON_ROOT / "seed.py"
COVERAGE_PY = CUMULUS_COMMON_ROOT / "coverage.py"
RECORD_ID_PY = CUMULUS_COMMON_ROOT / "record_id.py"

PROCEDURE_NAME = "SP_GENERATE_DEMANDBASE_INTENT_SIGNALS"
PROCEDURE_FQN = f"DATA_JEDAIS.FINS__PUBLIC.{PROCEDURE_NAME}"
TABLE_FQN = "DATA_JEDAIS.FINS__PUBLIC.DEMANDBASE_INTENT_SIGNALS"
TASK_NAME = "TASK_WEEKLY_DEMANDBASE_INTENT_SIGNALS"
DATASET_SALT = "demandbase"

SQL_HEADER = f"""\
-- =============================================================================
-- {PROCEDURE_FQN}  (Snowpark Python SP)
-- =============================================================================
-- Plan:    docs/superpowers/plans/2026-11-02-cumulus-plan-14-demandbase-intent-signals.md
-- Task:    Plan 14 T4 / T6
-- Source:  procedures/sp_generate_demandbase_intent_signals.py
--          (cumulus_common seed_for + assert_coverage + record_id_for inlined
--          so the SP body is self-contained -- no IMPORTS / no stage).
--          Generated by scripts/deploy_sp.py -- do NOT edit by hand.
--
-- Audience: ACCOUNT_TYPE_FLAG = 'BUSINESS'
--           AND COALESCE(CLIENT_CATEGORY, '') <> 'Household'
--           -- 6,435 anchors (probed 2026-11-02).
-- Cadence:  WEEKLY ({TASK_NAME}, Monday 03:15 America/New_York)
-- Salts:    "{DATASET_SALT}" (week-bucketed) + "demandbase_year" (year-stable)
-- Table:    {TABLE_FQN}
--           PK (ORG_ID, ACCOUNT_ID, PROFILE_WEEK, INTENT_TOPIC); DC PK RECORD_ID.
-- Shape:    Sparse 1:N, 1-4 topic rows per anchor-week. Each week is
--           rewritten wholesale: DELETE the week + INSERT, one transaction.
-- Arg:      BACKFILL_WEEKS (default 0 = current week; N = weeks W-N .. W).
--           One-shot backfill after deploy: CALL {PROCEDURE_FQN}(25);
-- Soft dep: GONG_CALL_SENTIMENT (Plan 12), probed; absent -> bias skipped.
-- =============================================================================

CREATE OR REPLACE PROCEDURE {PROCEDURE_FQN}(BACKFILL_WEEKS INTEGER DEFAULT 0)
RETURNS STRING
LANGUAGE PYTHON
RUNTIME_VERSION = '3.11'
PACKAGES = ('snowflake-snowpark-python', 'pandas')
HANDLER = 'main'
EXECUTE AS OWNER
AS
$$
"""

SQL_FOOTER = "$$;\n"

DROP_OLD_SIGNATURE_SQL = f"DROP PROCEDURE IF EXISTS {PROCEDURE_FQN}();\n\n"


def _strip_module_docstring_and_imports(src: str) -> str:
    src = re.sub(r'^\s*"""[\s\S]*?"""\s*\n', "", src, count=1)
    src = re.sub(r"^from __future__ import .*\n", "", src, flags=re.MULTILINE)
    src = re.sub(r"^from cumulus_common(?:\.[\w]+)? import .*\n", "", src, flags=re.MULTILINE)
    return src


def _extract_helper(src: str, func_name: str) -> str:
    """Extract a top-level `def func_name(...)` with its body (stops at the
    next column-0 non-blank, non-comment line)."""
    out: list[str] = []
    in_func = False
    for line in src.splitlines(keepends=True):
        if not in_func:
            if line.startswith(f"def {func_name}("):
                in_func = True
                out.append(line)
            continue
        if line and line[0] not in (" ", "\t", "\n", "#"):
            break
        out.append(line)
    if not out:
        raise RuntimeError(f"could not find `def {func_name}` in source")
    while out and out[-1].strip() == "":
        out.pop()
    return "".join(out) + "\n"


def build_sql(drop_old_signature: bool = False) -> str:
    sp_clean = _strip_module_docstring_and_imports(SP_PY.read_text())
    if re.search(r"^\s*(from|import) cumulus_common", sp_clean, flags=re.MULTILINE):
        raise RuntimeError("cumulus_common import survived stripping")

    helpers = []
    for path, name in ((SEED_PY, "seed_for"), (COVERAGE_PY, "assert_coverage"),
                       (RECORD_ID_PY, "record_id_for")):
        helpers.append(
            "# -------------------------------------------------------------------\n"
            f"# Inlined from cumulus_common.{path.stem} (kept in sync via scripts/deploy_sp.py)\n"
            "# -------------------------------------------------------------------\n"
            + _extract_helper(path.read_text(), name) + "\n"
        )
    inlined = "import hashlib\n\n" + "\n".join(helpers)

    lines = sp_clean.splitlines(keepends=True)
    last_import_idx = max((i for i, ln in enumerate(lines)
                           if ln.startswith("import ") or ln.startswith("from ")), default=-1)
    if last_import_idx < 0:
        raise RuntimeError("no import lines found in cleaned SP body -- refusing to splice")
    insert_at = last_import_idx + 1
    while insert_at < len(lines) and lines[insert_at].strip() == "":
        insert_at += 1

    body = ("from __future__ import annotations\n\n" + "".join(lines[:insert_at]) + "\n"
            + inlined + "\n" + "".join(lines[insert_at:]))
    sql = (DROP_OLD_SIGNATURE_SQL if drop_old_signature else "") + SQL_HEADER + body + SQL_FOOTER

    if "&" in sql:
        raise RuntimeError("ampersand in generated SQL (snow sql template-render trap)")
    if body.count("$$"):
        raise RuntimeError("'$$' inside the SP body would terminate the dollar-quoted source")
    return sql


def _snow() -> str:
    return shutil.which("snow") or "/opt/homebrew/bin/snow"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--connection", "-c", default=None,
                        help="snow CLI connection (default: unflagged = active JWT connection)")
    parser.add_argument("--no-deploy", action="store_true",
                        help="Generate sp_create_procedure.sql but skip snow sql -f.")
    parser.add_argument("--drop-old-signature", action="store_true",
                        help="Prepend DROP PROCEDURE IF EXISTS <sp>() (signature change).")
    args = parser.parse_args()

    for path in (SP_PY, SEED_PY, COVERAGE_PY, RECORD_ID_PY):
        if not path.exists():
            print(f"ERROR: {path} does not exist", file=sys.stderr)
            return 1

    print(f"Building {SP_SQL} from {SP_PY.name} + cumulus_common helpers ...")
    sql = build_sql(drop_old_signature=args.drop_old_signature)
    SP_SQL.write_text(sql)
    print(f"  wrote {SP_SQL} ({len(sql)} bytes)")
    if args.no_deploy:
        print("--no-deploy set; skipping snow sql.")
        return 0

    cmd = [_snow(), "sql", "-f", str(SP_SQL)]
    if args.connection:
        cmd[1:1] = ["-c", args.connection]
    print(f"Deploying SP via: {' '.join(cmd)}")
    rc = subprocess.call(cmd)
    if rc != 0:
        print(f"ERROR: snow sql exited with code {rc}", file=sys.stderr)
        return rc
    print("Deploy complete. Verify with:")
    print(f"  snow sql -q \"SHOW PROCEDURES LIKE '{PROCEDURE_NAME}' IN SCHEMA DATA_JEDAIS.FINS__PUBLIC\"")
    print(f"Then backfill once: snow sql -q \"CALL {PROCEDURE_FQN}(25)\"")
    return 0


if __name__ == "__main__":
    sys.exit(main())
