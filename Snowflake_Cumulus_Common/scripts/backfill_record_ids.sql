-- =============================================================================
-- Backfill RECORD_ID on all third-party enrichment tables.
--
-- Formula: SHA2(CONCAT_WS('|', <PK columns>, 'record_id'), 256) → first 32 hex
-- chars → UUID-formatted (8-4-4-4-12). Identical to cumulus_common.record_id_for().
--
-- Run once after ALTERing each table to add the column.
-- Safe to re-run — deterministic, so UPDATE is idempotent.
-- =============================================================================

-- Helper: inline macro for the UUID formatting
-- SHA2 → LEFT 32 → insert dashes at 8/12/16/20
