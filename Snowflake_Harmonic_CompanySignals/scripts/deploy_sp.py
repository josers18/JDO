#!/usr/bin/env python3
"""Deploy SP_GENERATE_HARMONIC_COMPANY_SIGNALS into DATA_JEDAIS.FINS__PUBLIC.

Generator-style sibling of Plan 11's `Snowflake_ZoomInfo_Firmographics/
scripts/deploy_sp.py`, with only the identifier constants, the SQL header
and the procedure signature changed.

What this script does:
  1. Reads the SP body from
     `procedures/sp_generate_harmonic_company_signals.py`.
  2. Reads `seed_for`, `assert_coverage` and `record_id_for` from
     `Snowflake_Cumulus_Common/cumulus_common/{seed,coverage,record_id}.py`.
  3. Strips the module docstring and the `from __future__` and
     `from cumulus_common` import lines from the SP body. The helpers are
     inlined, so there is no IMPORTS clause and no stage.
  4. Writes one inline-source `CREATE OR REPLACE PROCEDURE ...` file to
     `procedures/sp_create_procedure.sql`.
  5. Runs `snow sql -f procedures/sp_create_procedure.sql` UNFLAGGED, using
     the default JWT connection. It never passes `-c`, which triggers an
     OAuth popup. `--role` is passed through when given; the objects are
     owned by ACCOUNTADMIN.

Plan 16 deviations from the Plan 11 template:

  - **Signature takes an argument.** The procedure is
    `SP_GENERATE_HARMONIC_COMPANY_SIGNALS(BACKFILL_MONTHS INTEGER DEFAULT 0)`.
    The TASK calls the no-argument form (current month only). Task 6 runs
    `CALL ...(6)` once to backfill M-6..M. Snowflake overloads by argument
    types, so a leftover zero-argument `...()` procedure would be a second
    object rather than being replaced. Run `DROP PROCEDURE IF EXISTS ...()`
    once if an earlier no-argument version was ever deployed. Calling `()`
    resolves to the DEFAULT 0 form when no zero-argument overload exists.
  - **Two salts.** "harmonic" is the month-bucketed stream (headcount
    drift, job postings, refresh-date jitter). "harmonic_funding" is the
    account-stable funding timeline stream (rounds, amounts, investors),
    seeded with seed_for(account_id, "harmonic_funding", 2000-01-01). Each
    round then draws from a seed keyed on ACCOUNT_ID plus the round index,
    so the history never re-draws from month to month.
  - **Hard cross-plan dependencies.** The SP reads ZOOMINFO_FIRMOGRAPHICS
    (Plan 11) and MOODYS_MARKET_CONTEXT (Plan 13 v2), and raises before any
    write when either is missing, Moody's is empty, or ZoomInfo has no row
    for a target month.
  - **BOOLEAN column.** RECENTLY_FUNDED_FLAG is cast `::BOOLEAN` in the
    MERGE source SELECT, and the 3 DATE columns plus GENERATED_AT are cast
    back from nanosecond NUMBER (the write_pandas datetime64 mistype).
  - **No ampersand sanitize.** "Harmonic" is clean, and the generated file
    must contain no ampersand at all, because `snow sql -f` would treat it
    as a template variable. build_sql() refuses to emit one.

Usage:
    python scripts/deploy_sp.py [--no-deploy] [--role ROLE]
"""
from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys


REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
SP_PY = REPO_ROOT / "procedures" / "sp_generate_harmonic_company_signals.py"
SP_SQL = REPO_ROOT / "procedures" / "sp_create_procedure.sql"

CUMULUS_COMMON_ROOT = REPO_ROOT.parent / "Snowflake_Cumulus_Common" / "cumulus_common"
SEED_PY = CUMULUS_COMMON_ROOT / "seed.py"
COVERAGE_PY = CUMULUS_COMMON_ROOT / "coverage.py"
RECORD_ID_PY = CUMULUS_COMMON_ROOT / "record_id.py"

SNOW_BIN = "/opt/homebrew/bin/snow"

PROCEDURE_FQN = "DATA_JEDAIS.FINS__PUBLIC.SP_GENERATE_HARMONIC_COMPANY_SIGNALS"
PROCEDURE_SIGNATURE = "BACKFILL_MONTHS INTEGER DEFAULT 0"
TABLE_FQN = "DATA_JEDAIS.FINS__PUBLIC.HARMONIC_COMPANY_SIGNALS"
TASK_NAME = "TASK_MONTHLY_HARMONIC_COMPANY_SIGNALS"
DATASET_SALT = "harmonic"
FUNDING_SALT = "harmonic_funding"

SQL_HEADER = f"""\
-- =============================================================================
-- {PROCEDURE_FQN}  (Snowpark Python SP)
-- =============================================================================
-- Plan:    docs/superpowers/plans/2026-11-02-cumulus-plan-16-harmonic-company-signals.md
-- Task:    Plan 16 T4/T5
-- Source:  procedures/sp_generate_harmonic_company_signals.py
--          (cumulus_common.seed_for, assert_coverage and record_id_for are
--          inlined so the SP body is self-contained: no IMPORTS, no stage).
--          Generated by scripts/deploy_sp.py. Do NOT edit by hand.
--
-- Signature: ({PROCEDURE_SIGNATURE})
--           0 (the TASK path) = current UTC month only; N = months M-N..M.
-- Audience: plan section 2 SQL: young private commercial clients (BUSINESS
--           anchors in the Commercial categories, ZoomInfo FOUNDED_YEAR at
--           or after 2010, latest Moody's LIQUIDITY_TIER not 'Liquid').
-- Hard deps: ZOOMINFO_FIRMOGRAPHICS (Plan 11) and MOODYS_MARKET_CONTEXT
--           (Plan 13 v2). Missing table, empty Moody's or a ZoomInfo month
--           with no rows raises before any write.
-- Cadence:  MONTHLY ({TASK_NAME}), 1st of month at 09:00 UTC, after
--           ZoomInfo (07:00 UTC).
-- Salts:    "{DATASET_SALT}" (month-bucketed) and "{FUNDING_SALT}"
--           (account-stable funding timeline; per-round seed keyed on
--           ACCOUNT_ID plus the round index).
-- RECORD_ID: record_id_for(ORG_ID, ACCOUNT_ID, PROFILE_MONTH), written on
--           INSERT and UPDATE.
-- Table:    {TABLE_FQN}
--           MERGE key (ORG_ID, ACCOUNT_ID, PROFILE_MONTH). 1:1 per month.
-- Coverage: assert_coverage(section 2 audience, distinct accounts written)
--           for every target month after the MERGE.
-- Vendor:   Harmonic / Coresignal-style synthetic signals. No real vendor
--           data or license.
-- =============================================================================

CREATE OR REPLACE PROCEDURE {PROCEDURE_FQN}({PROCEDURE_SIGNATURE})
RETURNS STRING
LANGUAGE PYTHON
RUNTIME_VERSION = '3.11'
PACKAGES = ('snowflake-snowpark-python', 'pandas')
HANDLER = 'main'
EXECUTE AS OWNER
AS
$$
"""

SQL_FOOTER = "$$;\n"


def _strip_module_docstring_and_imports(src: str) -> str:
    src = re.sub(r'^\s*"""[\s\S]*?"""\s*\n', "", src, count=1)
    src = re.sub(r"^from __future__ import .*\n", "", src, flags=re.MULTILINE)
    src = re.sub(r"^from cumulus_common(?:\.[\w]+)? import .*\n", "", src, flags=re.MULTILINE)
    return src


def _extract_helper(src: str, func_name: str) -> str:
    """Extract a top-level `def func_name(...)` with its body."""
    lines = src.splitlines(keepends=True)
    out: list[str] = []
    in_func = False
    for line in lines:
        if not in_func:
            if line.startswith(f"def {func_name}("):
                in_func = True
                out.append(line)
            continue
        if line and line[0] not in (" ", "\t", "\n", "#"):
            break
        out.append(line)
    if not out:
        raise RuntimeError(f"could not find `def {func_name}` in source")
    while out and out[-1].strip() == "":
        out.pop()
    return "".join(out) + "\n"


def build_body() -> str:
    """The Python source that goes between the $$ delimiters."""
    sp_clean = _strip_module_docstring_and_imports(SP_PY.read_text())
    helpers = [
        ("seed", _extract_helper(SEED_PY.read_text(), "seed_for")),
        ("coverage", _extract_helper(COVERAGE_PY.read_text(), "assert_coverage")),
        ("record_id", _extract_helper(RECORD_ID_PY.read_text(), "record_id_for")),
    ]
    rule = "# -------------------------------------------------------------------\n"
    inlined = "import hashlib\n\n" + "".join(
        f"{rule}# Inlined from cumulus_common.{mod} (kept in sync via scripts/deploy_sp.py)\n{rule}{d}\n"
        for mod, d in helpers)

    lines = sp_clean.splitlines(keepends=True)
    last_import_idx = -1
    for i, line in enumerate(lines):
        if line.startswith("import ") or line.startswith("from "):
            last_import_idx = i
    if last_import_idx < 0:
        raise RuntimeError("no import lines found in cleaned SP body; refusing to splice")
    insert_at = last_import_idx + 1
    while insert_at < len(lines) and lines[insert_at].strip() == "":
        insert_at += 1

    return ("from __future__ import annotations\n\n"
            + "".join(lines[:insert_at]) + "\n" + inlined + "\n"
            + "".join(lines[insert_at:]))


def build_sql() -> str:
    sql = SQL_HEADER + build_body() + SQL_FOOTER
    if "&" in sql:
        raise RuntimeError("generated SQL contains an ampersand; snow sql -f would template it")
    if sql.count("$$") != 2:
        raise RuntimeError("generated SQL must contain exactly one $$ ... $$ body")
    return sql


def main() -> int:
    parser = argparse.ArgumentParser(description="Deploy SP_GENERATE_HARMONIC_COMPANY_SIGNALS")
    parser.add_argument("--no-deploy", action="store_true",
                        help="Generate sp_create_procedure.sql but skip running snow sql -f.")
    parser.add_argument("--role", default=None,
                        help="Optional role passed to snow sql (objects are owned by ACCOUNTADMIN).")
    args = parser.parse_args()

    for path in (SP_PY, SEED_PY, COVERAGE_PY, RECORD_ID_PY):
        if not path.exists():
            print(f"ERROR: {path} does not exist", file=sys.stderr)
            return 1

    sql = build_sql()
    SP_SQL.write_text(sql)
    print(f"wrote {SP_SQL} ({len(sql)} bytes)")
    if args.no_deploy:
        print("--no-deploy set; skipping snow sql.")
        return 0

    cmd = [SNOW_BIN, "sql", "-f", str(SP_SQL)]
    if args.role:
        cmd += ["--role", args.role]
    print(f"Deploying via: {' '.join(cmd)}")
    rc = subprocess.call(cmd)
    if rc != 0:
        print(f"ERROR: snow sql exited with code {rc}", file=sys.stderr)
    return rc


if __name__ == "__main__":
    sys.exit(main())
