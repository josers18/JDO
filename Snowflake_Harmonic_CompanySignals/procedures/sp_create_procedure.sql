        _check_dependencies(session, months)

        audiences = {}
        for m in months:
            audiences[m] = _load_audience(session, m)
            if not audiences[m]:
                raise RuntimeError(
                    f"empty audience for {m.isoformat()}: the section 2 join returned 0 anchors")
        zi_all = _load_zoominfo(session, months)

