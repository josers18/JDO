#!/usr/bin/env python3
"""Build (and optionally deploy) SP_GENERATE_PRODUCT_RECOMMENDATION_INPUTS.

Concatenates the `procedures/prodrec/` modules into ONE inline-source Snowpark
Python stored procedure (no stage, no IMPORTS), mirroring the sibling
`Snowflake_BoardEx_ExecIntel/scripts/deploy_sp.py`:

  1. Inline `seed_for` and `assert_coverage` from `Snowflake_Cumulus_Common`
     (via `_extract_helper`).
  2. Append common, vocab, business, personal, labels, training, sp_main in
     that order, with each module's docstring, `from __future__`,
     `from cumulus_common...` and `from prodrec...` / `import prodrec...`
     statements (including multi-line ones) removed. `from __future__ import
     annotations` is hoisted to the top.
  3. Write `procedures/sp_create_procedure.sql` (committed; a test keeps it
     in sync with `build_sql()`).
  4. Unless `--no-deploy`, run `snow sql -f` (optionally `--connection NAME`).

Usage:
    python scripts/deploy_sp.py [--connection NAME] [--no-deploy]
"""
from __future__ import annotations

import argparse
import ast
import pathlib
import re
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
PKG_DIR = REPO_ROOT / "procedures" / "prodrec"
SP_SQL = REPO_ROOT / "procedures" / "sp_create_procedure.sql"
MODULE_ORDER = ("common", "vocab", "business", "personal", "labels", "training", "sp_main")

CUMULUS_COMMON_ROOT = REPO_ROOT.parent / "Snowflake_Cumulus_Common" / "cumulus_common"
SEED_PY = CUMULUS_COMMON_ROOT / "seed.py"
COVERAGE_PY = CUMULUS_COMMON_ROOT / "coverage.py"

PROCEDURE_FQN = "DATA_JEDAIS.FINS__PUBLIC.SP_GENERATE_PRODUCT_RECOMMENDATION_INPUTS"

SQL_HEADER = f"""\
-- =============================================================================
-- {PROCEDURE_FQN}  (Snowpark Python SP)
-- =============================================================================
-- Generated by scripts/deploy_sp.py from procedures/prodrec/*.py (with
-- cumulus_common.seed_for and assert_coverage inlined). Do NOT edit by hand.
-- Modes: INPUTS (default, monthly task), TRAINING (manual), ALL.
-- =============================================================================

CREATE OR REPLACE PROCEDURE {PROCEDURE_FQN}(MODE STRING DEFAULT 'INPUTS')
RETURNS STRING
LANGUAGE PYTHON
RUNTIME_VERSION = '3.11'
PACKAGES = ('snowflake-snowpark-python', 'pandas')
HANDLER = 'main'
EXECUTE AS CALLER
AS
$$
"""
SQL_FOOTER = "$$;\n"

_INTERNAL_ROOTS = ("prodrec", "cumulus_common", "__future__")


def _is_internal_import(node: ast.stmt) -> bool:
    if isinstance(node, ast.ImportFrom):
        return node.level == 0 and (node.module or "").split(".")[0] in _INTERNAL_ROOTS
    if isinstance(node, ast.Import):
        return any(a.name.split(".")[0] in _INTERNAL_ROOTS for a in node.names)
    return False


def _strip_module(src: str) -> str:
    """Drop the module docstring and top-level internal imports (any line span)."""
    tree = ast.parse(src)
    drop: set[int] = set()
    for i, node in enumerate(tree.body):
        is_doc = (
            i == 0
            and isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        )
        if is_doc or _is_internal_import(node):
            drop.update(range(node.lineno, node.end_lineno + 1))
    lines = src.splitlines(keepends=True)
    return "".join(l for n, l in enumerate(lines, 1) if n not in drop).strip("\n") + "\n"


def _extract_helper(src: str, func_name: str) -> str:
    """Extract a top-level `def func_name(...)` with its body (sibling parity)."""
    lines = src.splitlines(keepends=True)
    out: list[str] = []
    in_func = False
    for line in lines:
        if not in_func:
            if line.lstrip().startswith(f"def {func_name}("):
                in_func = True
                out.append(line)
            continue
        if line and line[0] not in (" ", "\t", "\n", "#"):
            break
        out.append(line)
    if not out:
        raise RuntimeError(f"could not find `def {func_name}` in source")
    while out and out[-1].strip() == "":
        out.pop()
    return "".join(out) + "\n"


def _bare_ampersand(text: str) -> bool:
    """True if any `&` lacks a space on either side (`snow sql -f` templating)."""
    return re.search(r"(?<! )&|&(?! )", text) is not None


def _top_level_names(src: str) -> set[str]:
    names: set[str] = set()
    for node in ast.parse(src).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for t in targets:
                for n in ast.walk(t):
                    if isinstance(n, ast.Name):
                        names.add(n.id)
    return names


def check_name_collisions(sources: dict[str, str]) -> None:
    """Raise ValueError if a top-level name is defined in more than one source."""
    seen: dict[str, list[str]] = {}
    for label, src in sources.items():
        for name in _top_level_names(src):
            seen.setdefault(name, []).append(label)
    dups = {n: sorted(ls) for n, ls in seen.items() if len(ls) > 1}
    if dups:
        detail = "; ".join(f"{n} in {', '.join(ls)}" for n, ls in sorted(dups.items()))
        raise ValueError(f"top-level name collision across concatenated modules: {detail}")


def build_sql() -> str:
    helpers = (
        "import hashlib\n\n"
        "# Inlined from cumulus_common.seed\n"
        + _extract_helper(SEED_PY.read_text(), "seed_for")
        + "\n# Inlined from cumulus_common.coverage\n"
        + _extract_helper(COVERAGE_PY.read_text(), "assert_coverage")
    )
    check_name_collisions({
        "seed_for": _extract_helper(SEED_PY.read_text(), "seed_for"),
        "assert_coverage": _extract_helper(COVERAGE_PY.read_text(), "assert_coverage"),
        **{m: (PKG_DIR / f"{m}.py").read_text() for m in MODULE_ORDER},
    })
    parts = [
        f"# ---- prodrec.{name} ----\n" + _strip_module((PKG_DIR / f"{name}.py").read_text())
        for name in MODULE_ORDER
    ]
    body = "from __future__ import annotations\n\n" + helpers + "\n\n" + "\n\n".join(parts)
    if "$$" in body:
        raise RuntimeError("SP body contains '$$', which would end the procedure literal")
    if _bare_ampersand(body):
        raise RuntimeError("bare '&' in SP body; write 'and' (spaced ' & ' is allowed)")
    return SQL_HEADER + body + SQL_FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--connection", "-c", default=None,
        help="Snowflake CLI connection name (default: unflagged, active connection)",
    )
    parser.add_argument(
        "--no-deploy", action="store_true",
        help="Only generate procedures/sp_create_procedure.sql; do not run snow sql -f (no Snowflake access).",
    )
    args = parser.parse_args()

    for path in (SEED_PY, COVERAGE_PY, *(PKG_DIR / f"{m}.py" for m in MODULE_ORDER)):
        if not path.exists():
            print(f"ERROR: {path} does not exist", file=sys.stderr)
            return 1

    sql = build_sql()
    SP_SQL.write_text(sql)
    print(f"  wrote {SP_SQL} ({len(sql)} bytes)")

    if args.no_deploy:
        print("--no-deploy set; skipping snow sql.")
        return 0

    cmd = ["snow", "sql", "-f", str(SP_SQL)]
    if args.connection:
        cmd[1:1] = ["-c", args.connection]
    print(f"Deploying SP via: {' '.join(cmd)}")
    rc = subprocess.call(cmd)
    if rc != 0:
        print(f"ERROR: snow sql exited with code {rc}", file=sys.stderr)
    return rc


if __name__ == "__main__":
    sys.exit(main())
